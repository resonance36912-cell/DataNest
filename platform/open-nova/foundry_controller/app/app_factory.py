def _readme(spec: AppSpec) -> str:
    return (
        f"# {spec.title}\n\n"
        "Generated by Resonance Sovereign App Factory.\n\n"
        "## Intent\n\n"
        f"{spec.intent}\n\n"
        "## Sovereignty\n\n"
        "This project is portable source code. Its generated baseline does not require an external AI provider.\n"
    )


def _html(value: str) -> str:
    return (value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;").replace("'", "&#39;"))


def parse_project_proposal(raw: str, max_files: int = 60, max_total_bytes: int = 2_500_000) -> dict[str, str]:
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise GovernanceViolation("Local project generator returned invalid JSON.") from exc
    files = data.get("files") if isinstance(data, dict) else None
    if not isinstance(files, list) or not files:
        raise GovernanceViolation("Local project generator must return a non-empty files array.")
    if len(files) > max_files:
        raise GovernanceViolation(f"Local project generator proposed more than {max_files} files.")
    result: dict[str, str] = {}
    total = 0
    for item in files:
        if not isinstance(item, dict) or not isinstance(item.get("path"), str) or not isinstance(item.get("content"), str):
            raise GovernanceViolation("Every generated file requires string path and content fields.")
        path = _safe_relative_file(item["path"])
        if path in result:
            raise GovernanceViolation(f"Duplicate generated file path: {path}")
        content = item["content"]
        total += len(content.encode("utf-8"))
        if total > max_total_bytes:
            raise GovernanceViolation("Generated project exceeds governance total-size limit.")
        result[path] = content
    return result


def _safe_relative_file(path: str) -> str:
    normalized = path.replace("\\", "/").strip()
    pure = PurePosixPath(normalized)
    if not normalized or pure.is_absolute() or any(part in {"", ".", ".."} for part in pure.parts):
        raise GovernanceViolation(f"Unsafe generated relative path: {path}")
    if normalized.startswith(".git/") or normalized in {".env", ".env.sovereign"}:
        raise GovernanceViolation(f"Generated project may not create controller/security path: {path}")
    return str(pure)


def write_project(
    ws: SovereignWorkspace,
    spec: AppSpec,
    files: dict[str, str],
    *,
    overwrite: bool = False,
    confirmed: bool = False,
) -> list[dict[str, Any]]:
    """Write a generated project transactionally: partial writes are restored on denial/failure."""
    written: list[dict[str, Any]] = []
    originals: dict[str, tuple[bool, bytes | None]] = {}
    try:
        for rel, content in sorted(files.items()):
            safe = _safe_relative_file(rel)
            repo_path = f"{spec.project_dir}/{safe}"
            target = ws.resolve(repo_path)
            originals[repo_path] = (target.exists(), target.read_bytes() if target.exists() else None)
            written.append(ws.write_file(repo_path, content, overwrite=overwrite, confirmed=confirmed))
        return written
    except Exception:
        for repo_path, (existed, content) in reversed(list(originals.items())):
            target = ws.resolve(repo_path)
            if existed:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content or b"")
            elif target.exists():
                target.unlink()
        raise


def static_validate_project(project: Path) -> dict[str, Any]:
    findings: list[dict[str, Any]] = []
    files_checked = 0
    for path in project.rglob("*.py"):
        if not path.is_file():
            continue
        files_checked += 1
        try:
            ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        except (SyntaxError, UnicodeDecodeError) as exc:
            findings.append({"path": str(path.relative_to(project)).replace("\\", "/"), "type": "python_syntax", "detail": str(exc)})
    spec_path = project / "APP_SPEC.json"
    if not spec_path.exists():
        findings.append({"path": "APP_SPEC.json", "type": "missing_spec", "detail": "Controller app specification is missing."})
    else:
        try:
            json.loads(spec_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            findings.append({"path": "APP_SPEC.json", "type": "invalid_spec", "detail": str(exc)})
    return {"passed": not findings, "files_checked": files_checked, "findings": findings}


def preview_descriptor(spec: AppSpec, port_min: int = 4310, port_max: int = 4399) -> dict[str, Any]:
    if port_min < 1024 or port_max <= port_min:
        raise GovernanceViolation("Invalid governed preview port range.")
    span = port_max - port_min + 1
    offset = int(hashlib.sha256(spec.app_id.encode("utf-8")).hexdigest()[:8], 16) % span
    port = port_min + offset
    if spec.template == "python-fastapi":
        command = ["python", "-m", "uvicorn", "app:app", "--host", "127.0.0.1", "--port", str(port)]
    else:
        command = ["python", "-m", "http.server", str(port), "--bind", "127.0.0.1"]
    return {
        "mode": "local_loopback_only",
        "host": "127.0.0.1",
        "port": port,
        "url": f"http://127.0.0.1:{port}",
        "cwd": spec.project_dir,
        "command": command,
        "auto_started": False,
        "production": False,
    }
