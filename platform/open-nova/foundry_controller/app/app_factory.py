SUPPORTED_TEMPLATES = {"python-fastapi", "static-web"}


@dataclass(frozen=True)
class AppSpec:
    app_id: str
    title: str
    intent: str
    template: str
    project_dir: str
    external_ai_required: bool = False
    sovereignty_mode: str = "zero-credit"

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def make_spec(intent: str, app_name: str | None = None, template: str = "python-fastapi") -> AppSpec:
    cleaned_intent = intent.replace("\x00", "").strip()[:12000]
    if len(cleaned_intent) < 3:
        raise GovernanceViolation("Application intent is too short.")
    if template not in SUPPORTED_TEMPLATES:
        raise GovernanceViolation(f"Unsupported sovereign template: {template}")
    app_id = slugify(app_name or cleaned_intent.split(".")[0][:60])
    if not app_id:
        raise GovernanceViolation("Could not derive a safe application id.")
    title = " ".join(part.capitalize() for part in app_id.split("-"))
    return AppSpec(
        app_id=app_id,
        title=title,
        intent=cleaned_intent,
        template=template,
        project_dir=f"apps/{app_id}",
    )


